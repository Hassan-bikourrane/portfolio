/* =========================
   POSTER BOOK (page flip)
========================= */
(function () {
    const book = document.getElementById("poster-book");
    if (!book) return;

    const pages = [...book.querySelectorAll(".poster-page")];
    const n = pages.length;
    const counter = document.getElementById("poster-counter");
    let current = 0;
    let busy = false;

    function layout() {
        pages.forEach((page, i) => {
            const pos = (i - current + n) % n;
            page.style.setProperty("--pos", Math.min(pos, 3));
            page.style.zIndex = n - pos;
            page.classList.remove("is-flipping");
        });
        counter.textContent = `${current + 1} / ${n}`;
    }

    function next() {
        if (busy) return;
        busy = true;
        const top = pages[current];
        top.classList.add("is-flipping");
        setTimeout(() => {
            top.classList.add("no-anim");
            current = (current + 1) % n;
            layout();                 // flipped page drops to the bottom of the pile
            void top.offsetWidth;     // apply instantly, no animation
            top.classList.remove("no-anim");
            busy = false;
        }, 760);
    }

    function prev() {
        if (busy) return;
        busy = true;
        const back = pages[(current - 1 + n) % n];
        back.classList.add("no-anim", "is-flipping");
        back.style.zIndex = n + 1;
        void back.offsetWidth;
        back.classList.remove("no-anim");
        current = (current - 1 + n) % n;
        layout();                     // flips back onto the top
        setTimeout(() => { busy = false; }, 760);
    }

    document.getElementById("poster-next").addEventListener("click", next);
    document.getElementById("poster-prev").addEventListener("click", prev);
    book.addEventListener("click", next);
    book.style.cursor = "pointer";

    layout();
})();
