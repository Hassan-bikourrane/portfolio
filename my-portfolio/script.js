/* =========================
   2. LANGUAGE SWITCHER
========================= */

const languageSelect = document.getElementById("language-select");

function changeLanguage(language) {

    const selectedLanguage = translations[language];

    if (!selectedLanguage) return;

    const direction = language === "ar" ? "rtl" : "ltr";

    document.documentElement.lang = language;
    document.documentElement.dir = direction;
    document.body.dir = direction;

    document.querySelectorAll("[data-i18n]").forEach(element => {

        const key = element.dataset.i18n;

        if (Object.prototype.hasOwnProperty.call(selectedLanguage, key)) {
            element.textContent = selectedLanguage[key];
        }

    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {

        const key = element.dataset.i18nPlaceholder;

        if (Object.prototype.hasOwnProperty.call(selectedLanguage, key)) {
            element.placeholder = selectedLanguage[key];
        }

    });

    languageSelect.value = language;

    try {
        localStorage.setItem("portfolioLanguage", language);
    } catch (error) {
        console.warn("Language preference could not be saved.");
    }

}


/* Load saved language */

let savedLanguage = "en";

try {
    savedLanguage = localStorage.getItem("portfolioLanguage") || "en";
} catch (error) {
    console.warn("Language preference could not be loaded.");
}

changeLanguage(savedLanguage);

languageSelect.addEventListener("change", event => {
    changeLanguage(event.target.value);
});


/* =========================
   3. DARK / LIGHT THEME
========================= */

const themeToggle = document.getElementById("theme-toggle");
const themeIcon = themeToggle.querySelector("i");

let currentTheme = "dark";

try {
    currentTheme = localStorage.getItem("portfolio-theme") || "dark";
} catch (error) {
    currentTheme = "dark";
}

function applyTheme(theme) {

    currentTheme = theme;

    document.documentElement.dataset.theme = theme;

    const isLight = theme === "light";

    themeIcon.className = isLight
        ? "fa-solid fa-sun"
        : "fa-solid fa-moon";

    themeToggle.setAttribute(
        "aria-label",
        isLight ? "Switch to dark mode" : "Switch to light mode"
    );

    themeToggle.setAttribute("aria-pressed", String(isLight));

    try {
        localStorage.setItem("portfolio-theme", theme);
    } catch (error) {
        console.warn("Theme preference could not be saved.");
    }

}

applyTheme(currentTheme);

themeToggle.addEventListener("click", () => {

    const newTheme = currentTheme === "dark" ? "light" : "dark";

    applyTheme(newTheme);

});


